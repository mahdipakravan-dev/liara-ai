const NO_DOCUMENT_RULES = `
## قواعد استناد
- برای این پرسش هیچ بریده‌ای از مستندات لیارا در دسترس نیست.
- درباره‌ی جزئیات فنی لیارا از حافظه‌ات چیزی نساز. اگر مطمئن نیستی، بگو مطمئن نیستی و کاربر را به docs.liara.ir ارجاع بده.
- می‌توانی راهنمایی عمومی برنامه‌نویسی بدهی، اما صریح مشخص کن که توصیه‌ی کلی است و نه رفتار تأییدشده‌ی لیارا.
`.trim();

/** Numbered SOURCE blocks: the model needs a stable label to cite. */
function formatDocuments(documents) {
  if (!Array.isArray(documents) || documents.length === 0) return NO_DOCUMENT_RULES;

  const blocks = documents.map((document, index) => {
    const heading = document.heading ? ` › ${document.heading}` : "";
    return [
      `SOURCE ${index + 1}`,
      `Title: ${document.title}${heading}`,
      `URL: ${document.sourceUrl}`,
      "Content:",
      document.content,
    ].join("\n");
  });

  return [GROUNDING_RULES, "", "## مستندات لیارا", ...blocks].join("\n\n");
}

function formatIntent(intent, confidence) {
  const safeIntent = AGENT_INTENTS.includes(intent) ? intent : FALLBACK_INTENT;
  const lines = [
    `## موضوع تشخیص‌داده‌شده: ${safeIntent}`,
    INTENT_PLAYBOOKS[safeIntent],
  ];
  if (confidence === "low") lines.push(LOW_CONFIDENCE_NOTE);
  return lines.join("\n");
}

/** Persona + UI context + intent playbook + workflow + skill + docs. Missing pieces are skipped. */
export function buildSystemPrompt({
  context,
  intent,
  confidence,
  documents,
  skill,
  workflow,
  tools,
} = {}) {
  return [
    RAHYAR_PERSONA,
    formatAgentContext(context),
    formatIntent(intent, confidence),
    typeof workflow === "string" ? workflow.trim() : "",
    typeof skill === "string" ? skill.trim() : "",
    typeof tools === "string" ? tools.trim() : "",
    formatDocuments(documents),
  ]
    .filter(Boolean)
    .join("\n\n");
}
